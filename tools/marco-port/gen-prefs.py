"""Generate src/policy/marco-prefs.vala from Marco's GSettings schema.

    gen-prefs.py /usr/share/glib-2.0/schemas/org.mate.marco.gschema.xml \\
        > src/policy/marco-prefs.vala

The output is committed. `tests/vala/marco-prefs.vala` checks its defaults
against the installed schema, so changed Marco keys require regeneration.
"""

import html
import re
import sys

SCHEMAS = [
    ("general", "org.mate.Marco.general"),
    ("workspace-names", "org.mate.Marco.workspace-names"),
    ("global-keybindings", "org.mate.Marco.global-keybindings"),
    ("window-keybindings", "org.mate.Marco.window-keybindings"),
    ("keybinding-commands", "org.mate.Marco.keybinding-commands"),
]

# Schema enum names map to Vala names; placement_type uses the C enum read by
# the algorithms.
ENUM_TYPES = {
    "org.mate.Marco.FocusMode": "FocusMode",
    "org.mate.Marco.FocusNewWindows": "FocusNewWindows",
    "org.mate.Marco.WrapStyle": "WrapStyle",
    "org.mate.Marco.VisualBellType": "VisualBellType",
    "org.mate.Marco.ActionTitlebar": "TitlebarAction",
    "org.mate.Marco.placement_type": "Marco.PlacementMode",
}


def vala_ident(nick):
    return re.sub(r"[^A-Za-z0-9]+", "_", nick).upper()


def prop_name(key):
    return key.replace("-", "_")


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    xml = open(sys.argv[1], encoding="utf-8").read()

    enums = {}
    for m in re.finditer(r'<enum id="([^"]+)">(.*?)</enum>', xml, re.S):
        values = re.findall(r'<value (?:nick="([^"]+)" value="(\d+)"|value="(\d+)" nick="([^"]+)")',
                            m.group(2))
        enums[m.group(1)] = [(a or d, int(b or c)) for a, b, c, d in values]

    keys = []
    for short, schema_id in SCHEMAS:
        body = re.search(r'<schema id="%s".*?</schema>' % re.escape(schema_id), xml, re.S).group(0)
        for k in re.finditer(r'<key name="([^"]+)" (?:type="([^"]+)"|enum="([^"]+)")>(.*?)</key>',
                             body, re.S):
            default = html.unescape(re.search(r"<default>(.*?)</default>", k.group(4),
                                              re.S).group(1).strip())
            kind = k.group(2) or "enum:" + k.group(3)
            keys.append((short, k.group(1), kind, default))

    out = []
    w = out.append
    w("/*")
    w(" * Copyright 2026 Kerem Soke")
    w(" * SPDX-License-Identifier: GPL-3.0-or-later")
    w(" *")
    w(" * GENERATED by tools/marco-port/gen-prefs.py from org.mate.marco.gschema.xml")
    w(" * vala-lint=skip-file (generated data tables)")
    w(" * (Marco 1.28.2). Do not edit; re-run the generator.")
    w(" *")
    w(" * Polo.MarcoPrefs: an immutable snapshot of every org.mate.Marco.* key.")
    w(" * Policy decisions read a snapshot, never GSettings directly, so they are")
    w(" * deterministic and replayable.")
    w(" */")
    w("")
    w("namespace Polo {")
    for enum_id, vala in ENUM_TYPES.items():
        if vala.startswith("Marco."):
            continue
        values = enums[enum_id]
        w("    /* %s */" % enum_id)
        w("    public enum %s {" % vala)
        for i, (nick, value) in enumerate(values):
            sep = "," if i < len(values) - 1 else ";"
            w("        %s = %d%s" % (vala_ident(nick), value, sep))
        w("")
        w("        public static %s from_nick (string nick) {" % vala)
        w("            switch (nick) {")
        for nick, value in values:
            w('                case "%s": return %s;' % (nick, vala_ident(nick)))
            pass
        w("                default: return %s;" % vala_ident(values[0][0]))
        w("            }")
        w("        }")
        w("    }")
        w("")

    w("    public errordomain PrefsError {")
    w("        UNKNOWN_KEY,")
    w("        WRONG_TYPE,")
    w("        BAD_VALUE")
    w("    }")
    w("")
    w("    public class MarcoPrefs : GLib.Object {")
    w("        /* Every key as \"schema/key\", e.g. \"general/focus-mode\". */")
    w("        public const string[] KEYS = {")
    for short, key, kind, default in keys:
        w('            "%s/%s",' % (short, key))
    w("        };")
    w("")
    w("        /* GVariant text of each default, in KEYS order. */")
    w("        private const string[] DEFAULTS = {")
    for short, key, kind, default in keys:
        w("            %s," % ('"' + default.replace("\\", "\\\\").replace('"', '\\"') + '"'))
    w("        };")
    w("")
    w("        /* GVariant type of each key; enums are stored as their nick (\"s\"). */")
    w("        private const string[] TYPES = {")
    for short, key, kind, default in keys:
        w('            "%s",' % ("s" if kind.startswith("enum:") else kind))
    w("        };")
    w("")
    w("        /* Allowed nicks of enum keys, as \"schema/key=nick,nick\". */")
    w("        private const string[] ENUM_NICKS = {")
    for short, key, kind, default in keys:
        if kind.startswith("enum:"):
            nicks = ",".join(n for n, _ in enums[kind[5:]])
            w('            "%s/%s=%s",' % (short, key, nicks))
    w("        };")
    w("")
    w("        private GLib.HashTable<string, GLib.Variant> values;")
    w("")
    w("        private MarcoPrefs () {")
    w("            values = new GLib.HashTable<string, GLib.Variant> (GLib.str_hash, GLib.str_equal);")
    w("            for (int i = 0; i < KEYS.length; i++) {")
    w("                try {")
    w("                    values.insert (KEYS[i], GLib.Variant.parse (new GLib.VariantType (TYPES[i]),")
    w("                                                                DEFAULTS[i]));")
    w("                } catch (GLib.VariantParseError e) {")
    w('                    GLib.error ("bad generated default for %s: %s", KEYS[i], e.message);')
    w("                }")
    w("            }")
    w("        }")
    w("")
    w("        /* Marco's defaults. */")
    w("        public static MarcoPrefs defaults () {")
    w("            return new MarcoPrefs ();")
    w("        }")
    w("")
    w("        /*")
    w("         * Defaults with some keys replaced. Each value must have the key's")
    w("         * type; enum keys take their nick as a string.")
    w("         */")
    w("        public static MarcoPrefs with_overrides (GLib.HashTable<string, GLib.Variant> overrides)")
    w("                throws PrefsError {")
    w("            var prefs = new MarcoPrefs ();")
    w("            foreach (unowned string key in overrides.get_keys ()) {")
    w("                prefs.set_checked (key, overrides[key]);")
    w("            }")
    w("            return prefs;")
    w("        }")
    w("")
    w("        private void set_checked (string key, GLib.Variant value) throws PrefsError {")
    w("            unowned GLib.Variant? current = values.lookup (key);")
    w("            if (current == null) {")
    w('                throw new PrefsError.UNKNOWN_KEY ("no Marco key %s", key);')
    w("            }")
    w("            if (!value.get_type ().equal (current.get_type ())) {")
    w('                throw new PrefsError.WRONG_TYPE ("%s wants %s, got %s", key,')
    w("                                                 current.get_type_string (),")
    w("                                                 value.get_type_string ());")
    w("            }")
    w("            foreach (unowned string spec in ENUM_NICKS) {")
    w('                if (spec.has_prefix (key + "=")) {')
    w('                    var nicks = spec.substring (key.length + 1).split (",");')
    w("                    if (!(value.get_string () in nicks)) {")
    w('                        throw new PrefsError.BAD_VALUE ("%s has no value \\"%s\\"", key,')
    w("                                                        value.get_string ());")
    w("                    }")
    w("                }")
    w("            }")
    w("            values.insert (key, value);")
    w("        }")
    w("")
    w("        /* The value of \"schema/key\"; null if there is no such key. */")
    w("        public GLib.Variant? get_value (string key) {")
    w("            return values.lookup (key);")
    w("        }")
    w("")
    w("        public string get_keybinding (string schema, string name) {")
    w('            var value = values.lookup (schema + "/" + name);')
    w('            return value != null ? value.get_string () : "disabled";')
    w("        }")
    w("")
    w("        /* Workspace names are 1-based in the schema. */")
    w("        public string workspace_name (int index) {")
    w('            var value = values.lookup ("workspace-names/name-%d".printf (index + 1));')
    w('            return value != null ? value.get_string () : "";')
    w("        }")
    w("")
    w("        /* The part the C algorithms read. */")
    w("        public Marco.Prefs to_c () {")
    w("            return Marco.Prefs () {")
    w("                placement_mode = placement_mode,")
    w("                center_new_windows = center_new_windows,")
    w("                allow_tiling = allow_tiling,")
    w("                allow_top_tiling = allow_top_tiling,")
    w("                allow_tile_cycling = allow_tile_cycling,")
    w("                disable_workarounds = disable_workarounds")
    w("            };")
    w("        }")
    w("")
    w("        private bool boolean (string key) {")
    w("            return values[key].get_boolean ();")
    w("        }")
    w("")
    w("        private int integer (string key) {")
    w("            return values[key].get_int32 ();")
    w("        }")
    w("")
    w("        private string text (string key) {")
    w("            return values[key].get_string ();")
    w("        }")
    w("")
    w("        /* ---- org.mate.Marco.general ---- */")
    for short, key, kind, default in keys:
        if short != "general":
            continue
        path = "general/" + key
        name = prop_name(key)
        if kind == "b":
            w('        public bool %s { get { return boolean ("%s"); } }' % (name, path))
        elif kind == "i":
            w('        public int %s { get { return integer ("%s"); } }' % (name, path))
        elif kind == "s":
            w('        public string %s { owned get { return text ("%s"); } }' % (name, path))
        else:
            vala = ENUM_TYPES[kind[5:]]
            if vala == "Marco.PlacementMode":
                w("        public Marco.PlacementMode %s {" % name)
                w("            get {")
                w('                switch (text ("%s")) {' % path)
                for nick, value in enums[kind[5:]]:
                    w('                    case "%s": return Marco.PlacementMode.%s;'
                      % (nick, vala_ident(nick)))
                w("                    default: return Marco.PlacementMode.AUTOMATIC;")
                w("                }")
                w("            }")
                w("        }")
            else:
                w("        public %s %s {" % (vala, name))
                w('            get { return %s.from_nick (text ("%s")); }' % (vala, path))
                w("        }")
    w("    }")
    w("}")
    sys.stdout.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
